"""PDF report generators for dossiers (fpdf2 — MIT licensed, zero cost).

Two generators:
  * match_report_pdf(data)          -> bytes  (match summary, fights, rotations)
  * team_dossier_pdf(team_name, dossier) -> bytes (playstyle, edges, h2h)

Both accept plain dicts (e.g. ``MatchReportData.model_dump()``) so they are
usable without a database. When data is missing the page says so honestly —
never blank, never fabricated.

Compression is disabled so report text stays searchable/verifiable.
"""

from __future__ import annotations

from typing import Any, Optional

from fpdf import FPDF
from fpdf.enums import MethodReturnValue, XPos, YPos

# ── palette ───────────────────────────────────────────────────────────
NAVY = (13, 25, 48)
NAVY_LIGHT = (30, 48, 84)
ACCENT = (0, 176, 200)
INK = (20, 22, 28)
MUTED = (110, 118, 132)
ROW_ALT = (236, 239, 243)
LINE = (200, 206, 214)
WHITE = (255, 255, 255)
GREEN = (22, 130, 80)
RED = (178, 44, 44)
BLUE = (36, 90, 178)
GRAY = (120, 128, 140)

PAGE_W = 210
MARGIN = 12
CONTENT_W = PAGE_W - 2 * MARGIN


def _safe(text: Any) -> str:
    """Core font Helvetica is latin-1 only — degrade gracefully, never crash."""
    if text is None:
        return ""
    return str(text).encode("latin-1", "replace").decode("latin-1")


def _fmt_ts(ms: Optional[int]) -> str:
    if ms is None:
        return "n/a"
    s = ms // 1000
    return f"{s // 60:02d}:{s % 60:02d}"


class AegisPDF(FPDF):
    """Base PDF with the AEGIS header bar + page-number footer."""

    report_title: str = ""

    def __init__(self, report_title: str = "") -> None:
        super().__init__(orientation="P", unit="mm", format="A4")
        self.report_title = report_title
        self.set_compression(False)
        self.set_auto_page_break(True, margin=18)
        self.set_margins(MARGIN, 14, MARGIN)
        self.alias_nb_pages()

    # ── chrome ────────────────────────────────────────────────────
    def header(self) -> None:
        self.set_fill_color(*NAVY)
        self.set_xy(0, 0)
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(*WHITE)
        self.cell(PAGE_W, 11, "", fill=True, new_x=XPos.LEFT, new_y=YPos.TOP)
        self.set_xy(6, 2.2)
        self.cell(80, 7, "AEGIS AI", new_x=XPos.RIGHT, new_y=YPos.TOP)
        self.set_font("Helvetica", "", 8)
        self.set_x(PAGE_W - 86)
        self.cell(80, 7, _safe(self.report_title), align="R",
                   new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_fill_color(*ACCENT)
        self.set_xy(0, 11)
        self.cell(PAGE_W, 1.2, "", fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_y(15)

    def footer(self) -> None:
        self.set_y(-14)
        self.set_font("Helvetica", "", 7.5)
        self.set_text_color(*MUTED)
        self.cell(0, 5, f"Page {self.page_no()} of {{nb}}",
                   align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.cell(0, 4, _safe("Generated by AEGIS AI dossiers module - data as recorded, never estimated."),
                   align="C")

    # ── building blocks ───────────────────────────────────────────
    def cover_title(self, kicker: str, title: str, subtitle_lines: list[str]) -> None:
        self.ln(18)
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(*ACCENT)
        self.cell(0, 8, _safe(kicker).upper(), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_font("Helvetica", "B", 30)
        self.set_text_color(*NAVY)
        self.multi_cell(0, 13, _safe(title), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(4)
        self.set_draw_color(*ACCENT)
        self.set_line_width(1.1)
        self.line(MARGIN, self.get_y(), MARGIN + 40, self.get_y())
        self.ln(6)
        self.set_font("Helvetica", "", 11)
        self.set_text_color(*INK)
        for line in subtitle_lines:
            self.cell(0, 7, _safe(line), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(10)

    def section(self, title: str) -> None:
        if self.get_y() > 250:
            self.add_page()
        self.set_font("Helvetica", "B", 12)
        self.set_text_color(*NAVY)
        self.cell(0, 9, _safe(title), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_draw_color(*LINE)
        self.set_line_width(0.3)
        self.line(MARGIN, self.get_y(), PAGE_W - MARGIN, self.get_y())
        self.ln(3)

    def body(self, text: str) -> None:
        self.set_font("Helvetica", "", 9.5)
        self.set_text_color(*INK)
        self.multi_cell(0, 5.5, _safe(text), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(1)

    def bullet(self, text: str) -> None:
        self.set_font("Helvetica", "", 9.5)
        self.set_text_color(*INK)
        x = self.get_x()
        self.cell(6, 5.5, "-", new_x=XPos.RIGHT, new_y=YPos.TOP)
        self.multi_cell(CONTENT_W - 6, 5.5, _safe(text),
                        new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_x(x)

    def empty_note(self, text: str) -> None:
        self.set_fill_color(*ROW_ALT)
        self.set_font("Helvetica", "I", 9.5)
        self.set_text_color(*MUTED)
        self.multi_cell(0, 7, _safe(text), fill=True,
                        new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(2)

    def table(self, headers: list[str], rows: list[list[Any]],
              widths: list[float]) -> None:
        """Header row (navy) + alternating row shading. Auto page-breaks."""
        self.set_font("Helvetica", "B", 8.5)
        self.set_text_color(*WHITE)
        self.set_fill_color(*NAVY_LIGHT)
        for h, w in zip(headers, widths):
            self.cell(w, 7.5, _safe(h), border=0, fill=True, align="C",
                       new_x=XPos.RIGHT, new_y=YPos.TOP)
        self.ln()
        self.set_font("Helvetica", "", 8.5)
        self.set_text_color(*INK)
        for i, row in enumerate(rows):
            if self.get_y() > 268:
                self.add_page()
                # repeat header on the new page
                self.set_font("Helvetica", "B", 8.5)
                self.set_text_color(*WHITE)
                self.set_fill_color(*NAVY_LIGHT)
                for h, w in zip(headers, widths):
                    self.cell(w, 7.5, _safe(h), border=0, fill=True, align="C",
                               new_x=XPos.RIGHT, new_y=YPos.TOP)
                self.ln()
                self.set_font("Helvetica", "", 8.5)
                self.set_text_color(*INK)
            fill = (i % 2 == 1)
            if fill:
                self.set_fill_color(*ROW_ALT)
            # compute row height from wrapped cells
            h = 6.5
            x0 = self.get_x()
            y0 = self.get_y()
            max_lines = 1
            for val, w in zip(row, widths):
                lines = self.multi_cell(w, h, _safe(val), dry_run=True,
                                        output=MethodReturnValue.LINES)
                max_lines = max(max_lines, len(lines))
            rh = h * max_lines
            for j, (val, w) in enumerate(zip(row, widths)):
                self.set_xy(x0 + sum(widths[:j]), y0)
                align = "L" if j == 0 else "C"
                self.multi_cell(w, h, _safe(val), align=align, fill=fill,
                                new_x=XPos.RIGHT, new_y=YPos.TOP,
                                max_line_height=h)
            self.set_xy(x0, y0 + rh)
        self.ln(4)

    def badge(self, text: str, color: tuple[int, int, int]) -> None:
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(*WHITE)
        self.set_fill_color(*color)
        w = self.get_string_width(_safe(text)) + 10
        self.cell(w, 8, _safe(text), fill=True, align="C",
                   new_x=XPos.RIGHT, new_y=YPos.TOP)
        self.set_text_color(*INK)

    def kv(self, label: str, value: str) -> None:
        self.set_font("Helvetica", "B", 9.5)
        self.set_text_color(*MUTED)
        lw = self.get_string_width(label) + 4
        self.cell(lw, 6, _safe(label) + "  ", new_x=XPos.RIGHT, new_y=YPos.TOP)
        self.set_font("Helvetica", "", 9.5)
        self.set_text_color(*INK)
        self.multi_cell(CONTENT_W - lw, 6, _safe(value),
                        new_x=XPos.LMARGIN, new_y=YPos.NEXT)


# ── public generators ─────────────────────────────────────────────────


def match_report_pdf(data: dict[str, Any]) -> bytes:
    """Build a match report PDF from a MatchReportData-style dict."""
    pdf = AegisPDF(report_title="Match Report")
    pdf.add_page()

    match_no = data.get("match_number")
    title_bits = [f"Match {match_no}" if match_no else "Match"]
    pdf.cover_title(
        kicker="AEGIS AI — Match Report",
        title=" ".join(title_bits),
        subtitle_lines=[
            f"Tournament: {data.get('tournament_name') or 'Unknown tournament'}",
            f"Map: {data.get('map_name') or 'Unknown map'}",
            f"Played: {data.get('played_at') or 'not recorded'}",
        ],
    )

    # — summary —
    pdf.section("Match Summary")
    summaries: list[dict[str, Any]] = data.get("team_summaries") or []
    if summaries:
        rows = [
            [
                s.get("team_name") or s.get("team_id"),
                s.get("placement") if s.get("placement") is not None else "not recorded",
                s.get("kills", 0),
            ]
            for s in summaries
        ]
        pdf.table(["Team", "Placement", "Kills"], rows, [110, 40, 36])
    else:
        pdf.empty_note("No team summaries available for this match — "
                       "no teams, fights or kills were recorded.")

    # — key fights —
    pdf.section("Key Fights")
    fights: list[dict[str, Any]] = data.get("fights") or []
    if fights:
        rows = []
        for i, f in enumerate(fights, 1):
            team_names = " vs ".join(t.get("team_name", "?") for t in f.get("teams", [])) or "—"
            rows.append([
                i,
                _fmt_ts(f.get("start_timestamp_ms")),
                team_names,
                f.get("outcome") or "—",
                f.get("total_kills", 0),
                f"{(f.get('intensity_score') or 0):.2f}",
            ])
        pdf.table(["#", "Start", "Teams", "Outcome", "Kills", "Intensity"], rows,
                  [10, 18, 78, 44, 16, 20])
    else:
        pdf.empty_note("No fight events recorded for this match.")

    # — rotations —
    pdf.section("Rotation Highlights")
    rots: list[dict[str, Any]] = data.get("rotation_highlights") or []
    if rots:
        for r in rots:
            pdf.bullet(
                f"{r.get('team')}: {r.get('rotations')} rotation(s) — first at "
                f"{_fmt_ts(r.get('first_rotation_at_ms'))}, last at "
                f"{_fmt_ts(r.get('last_rotation_at_ms'))}"
            )
        pdf.ln(2)
    else:
        pdf.empty_note("No rotation events recorded for this match.")

    # — notes —
    pdf.section("Notes")
    notes: list[str] = data.get("notes") or []
    if notes:
        for n in notes:
            pdf.bullet(n)
    else:
        pdf.body("None.")

    return bytes(pdf.output())


_PLAYSTYLE_COLORS = {
    "aggressive": RED,
    "balanced": GREEN,
    "passive": BLUE,
    "insufficient_data": GRAY,
}


def team_dossier_pdf(team_name: str, dossier: dict[str, Any]) -> bytes:
    """Build a team dossier PDF from a DossierOut-style dict."""
    pdf = AegisPDF(report_title="Team Dossier")
    pdf.add_page()

    playstyle = dossier.get("playstyle") or {}
    label = playstyle.get("label", "insufficient_data")
    color = _PLAYSTYLE_COLORS.get(label, GRAY)

    pdf.cover_title(
        kicker="AEGIS AI — Team Dossier",
        title=team_name or "Unknown team",
        subtitle_lines=[
            f"Computed: {dossier.get('computed_at') or 'unknown'}",
            f"Matches sampled: {dossier.get('matches_sampled', 0)}   "
            f"Fights sampled: {dossier.get('fights_sampled', 0)}",
        ],
    )
    pdf.badge(label.replace("_", " ").upper(), color)
    pdf.ln(4)
    pdf.body(f"Playstyle evidence: {playstyle.get('evidence') or 'none recorded'}")

    # — strengths / weaknesses —
    pdf.section("Strengths — top statistical edges vs tournament average")
    strengths: list[dict[str, Any]] = dossier.get("strengths") or []
    if strengths:
        pdf.table(
            ["Edge", "Team", "Tournament avg", "Delta"],
            [[s.get("label"), s.get("team_value"), s.get("tournament_avg"),
              f"{s.get('delta_pct')}%" if s.get("delta_pct") is not None else "—"]
             for s in strengths],
            [100, 28, 32, 26],
        )
    else:
        pdf.empty_note("Insufficient data for strengths — need >= 5 fights "
                       "and >= 2 teams in the sampled matches.")

    pdf.section("Weaknesses — bottom statistical gaps vs tournament average")
    weaknesses: list[dict[str, Any]] = dossier.get("weaknesses") or []
    if weaknesses:
        pdf.table(
            ["Gap", "Team", "Tournament avg", "Delta"],
            [[w.get("label"), w.get("team_value"), w.get("tournament_avg"),
              f"{w.get('delta_pct')}%" if w.get("delta_pct") is not None else "—"]
             for w in weaknesses],
            [100, 28, 32, 26],
        )
    else:
        pdf.empty_note("Insufficient data for weaknesses — need >= 5 fights "
                       "and >= 2 teams in the sampled matches.")
    if dossier.get("comparison_note"):
        pdf.body(dossier["comparison_note"])

    # — tendencies —
    pdf.section("Tendencies")
    tend = dossier.get("tendencies") or {}
    drops = tend.get("drop_locations") or []
    pdf.kv("Drop locations", "")
    if drops:
        for d in drops:
            pdf.bullet(f"{d.get('location')}: {d.get('matches')} match(es)")
    pdf.body(tend.get("drop_location_note") or "")
    timing = tend.get("rotation_timing") or {}
    pdf.kv("Rotation timing",
           f"{timing.get('label', 'unknown')} — {timing.get('note', '')}".strip(" —"))
    central = tend.get("centrality") or {}
    pdf.kv("Map centrality",
           f"{central.get('label', 'unknown')} — {central.get('note', '')}".strip(" —"))

    # — head-to-head —
    pdf.section("Head-to-Head")
    h2h: list[dict[str, Any]] = dossier.get("head_to_head") or []
    if h2h:
        pdf.table(
            ["Opponent", "Fights", "W", "L", "Diseng.", "K for", "K agst"],
            [[h.get("opponent_name"), h.get("fights"), h.get("won"), h.get("lost"),
              h.get("disengaged"), h.get("kills_for"), h.get("kills_against")]
             for h in h2h],
            [72, 18, 14, 14, 20, 18, 18],
        )
    else:
        pdf.empty_note("No head-to-head fights recorded against other teams.")

    # — notes —
    pdf.section("Analyst Notes")
    notes: list[str] = dossier.get("notes") or []
    if notes:
        for n in notes:
            pdf.bullet(n)
    else:
        pdf.body("None.")

    return bytes(pdf.output())
